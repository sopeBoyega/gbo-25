BEGIN;
CREATE SCHEMA IF NOT EXISTS gbo;
CREATE TABLE IF NOT EXISTS gbo.entries (
 seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id text NOT NULL UNIQUE, request_id text NOT NULL UNIQUE,
 name text NOT NULL CHECK (length(name) BETWEEN 1 AND 60),
 message text NOT NULL CHECK (length(message) BETWEEN 2 AND 1200),
 photo bytea, status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved')),
 created_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS entries_status_seq ON gbo.entries(status,seq DESC);
CREATE TABLE IF NOT EXISTS gbo.limits (key text PRIMARY KEY,count integer NOT NULL,expires bigint NOT NULL);
CREATE TABLE IF NOT EXISTS gbo.sessions (token text PRIMARY KEY,expires bigint NOT NULL);
ALTER TABLE gbo.entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE gbo.limits ENABLE ROW LEVEL SECURITY;
ALTER TABLE gbo.sessions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON SCHEMA gbo FROM PUBLIC,anon,authenticated;

CREATE OR REPLACE FUNCTION public.gbo_query(q text,params jsonb DEFAULT '[]'::jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=gbo,pg_temp AS $$
DECLARE allowed text[] := ARRAY[
    'DELETE FROM limits WHERE expires < ?',
    'INSERT INTO limits(key,count,expires) VALUES (?,1,?) ON CONFLICT(key) DO UPDATE SET count=count+1',
    'SELECT count FROM limits WHERE key=?',
    'SELECT token FROM sessions WHERE token=? AND expires>?',
    'SELECT 1',
    'SELECT seq,id,name,message,created_at,photo IS NOT NULL AS has_photo FROM entries WHERE status=''approved'' AND seq < ? ORDER BY seq DESC LIMIT 25',
    'SELECT seq,id,name,message,created_at,photo IS NOT NULL AS has_photo FROM entries WHERE status=''approved'' AND seq < ? AND photo IS NOT NULL ORDER BY seq DESC LIMIT 25',
    'SELECT count(*) AS wishes,coalesce(sum(photo IS NOT NULL),0) AS photos FROM entries WHERE status=''approved''',
    'SELECT id FROM entries WHERE request_id=?',
    'SELECT count(*) AS n,coalesce(sum(length(photo)),0) AS bytes FROM entries',
    'INSERT INTO entries(id,request_id,name,message,photo,created_at) VALUES (?,?,?,?,?,?)',
    'DELETE FROM sessions WHERE expires < ?',
    'INSERT INTO sessions(token,expires) VALUES (?,?)',
    'DELETE FROM sessions WHERE token=?',
    'SELECT seq,id,name,message,status,created_at,photo IS NOT NULL AS has_photo FROM entries WHERE status=? AND seq<? ORDER BY seq DESC LIMIT 25',
    'DELETE FROM entries WHERE id=?',
    'UPDATE entries SET status=? WHERE id=?',
    'SELECT photo FROM entries WHERE id=?',
    'SELECT photo FROM entries WHERE id=? AND status=''approved'''
];
 parts text[]; statement text; i integer; changes bigint; output jsonb;
BEGIN
 IF NOT (q=ANY(allowed)) THEN RAISE EXCEPTION 'Query not allowed'; END IF;
 parts:=string_to_array(q,'?');
 IF jsonb_array_length(params)<>cardinality(parts)-1 THEN RAISE EXCEPTION 'Invalid parameters'; END IF;
 statement:=parts[1];
 FOR i IN 1..cardinality(parts)-1 LOOP
  statement:=statement||quote_nullable(params->>(i-1))||parts[i+1];
 END LOOP;
 statement:=replace(statement,'sum(photo IS NOT NULL)','sum(CASE WHEN photo IS NOT NULL THEN 1 ELSE 0 END)');
 statement:=replace(statement,'sum(length(photo))','sum(octet_length(photo))');
 statement:=replace(statement,'count=count+1','count=limits.count+1');
 IF q LIKE 'INSERT INTO entries%' THEN
  -- Serialize capacity checks across concurrent application instances.
  PERFORM pg_advisory_xact_lock(250025);
  IF (SELECT count(*) FROM entries)>=3000 OR
     (SELECT coalesce(sum(octet_length(photo)),0) FROM entries)+coalesce(octet_length((params->>4)::bytea),0)>268435456
  THEN RAISE EXCEPTION 'Archive capacity reached'; END IF;
 END IF;
 IF q LIKE 'SELECT %' THEN
  EXECUTE 'SELECT coalesce(jsonb_agg(to_jsonb(t)),''[]''::jsonb) FROM ('||statement||') t' INTO output;
  RETURN output;
 END IF;
 EXECUTE statement;
 GET DIAGNOSTICS changes=ROW_COUNT;
 RETURN jsonb_build_object('changes',changes);
END;
$$;
REVOKE ALL ON FUNCTION public.gbo_query(text,jsonb) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.gbo_query(text,jsonb) TO service_role;
COMMIT;
